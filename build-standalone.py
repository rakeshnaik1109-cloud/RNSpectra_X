#!/usr/bin/env python3
"""
Rebuild dist/rnspectrax-standalone.html from the modular source.

The single-file build exists so a collaborator or reviewer can be handed one
attachment and open it. Run this after changing anything in css/ or js/:

    python3 build-standalone.py
"""
import base64
import os
import re

os.chdir(os.path.dirname(os.path.abspath(__file__)))

# Cache-busting: stamp every css/js/data link in index.html with ?v=<build
# time>, so browsers fetch the new files after an update instead of reusing
# cached copies (GitHub Pages lets browsers cache them for a while).
import time
build_id = time.strftime('%Y%m%d%H%M', time.gmtime())
page = open('index.html', encoding='utf-8').read()
page = re.sub(r'((?:src|href)="(?:css|js|data)/[^"?]+)(?:\?v=[^"]*)?"', lambda m: '%s?v=%s"' % (m.group(1), build_id), page)
open('index.html', 'w', encoding='utf-8').write(page)

src = page


def inline_css(match):
    path = match.group(1)
    return '<style>\n/* %s */\n%s\n</style>' % (path, open(path, encoding='utf-8').read())


def inline_js(match):
    path = match.group(1)
    return '<script>\n/* %s */\n%s\n</script>' % (path, open(path, encoding='utf-8').read())


src = re.sub(r'<link href="(css/[^"?]+)(?:\?v=[^"]*)?" rel="stylesheet"/>', inline_css, src)
src = re.sub(r'<link rel="stylesheet" href="(css/[^"?]+)(?:\?v=[^"]*)?"\s*/?>', inline_css, src)
src = re.sub(r'<script src="(js/[^"?]+)(?:\?v=[^"]*)?"></script>', inline_js, src)

icon = base64.b64encode(open('assets/favicon.svg', encoding='utf-8').read().encode()).decode()
src = src.replace('<link rel="icon" href="assets/favicon.svg" type="image/svg+xml"/>',
                  '<link rel="icon" href="data:image/svg+xml;base64,%s" type="image/svg+xml"/>' % icon)
src = src.replace('href="guide.html"', 'href="https://rakeshnaik1109-cloud.github.io/RNSpectra_X/guide.html"')
src = src.replace('<head>', '<head>\n<script>window.RNSX_GUIDE_URL = "https://rakeshnaik1109-cloud.github.io/RNSpectra_X/guide.html";</script>', 1)
src = src.replace('href="docs/USER_MANUAL.md"',
                  'href="https://github.com/rakeshnaik1109-cloud/RNSpectra_X/blob/main/docs/USER_MANUAL.md"')

# Reference library for "Identify": embedded as inline JSON so the single
# file also works offline (the modular app loads data/ramanbiolib.js on demand).
lib_js = open('data/ramanbiolib.js', encoding='utf-8').read()
lib_json = lib_js.split('window.RNSPX_LIBRARY_RAMANBIOLIB = ', 1)[1].rstrip().rstrip(';')
src = src.replace('</body>', '<script type="application/json" id="rnspxLibraryData">%s</script>\n</body>' % lib_json.replace('</', '<\\/'), 1)

banner = ("<!-- RNSpectraX 3.4 — single-file build.\n"
          "     Generated by build-standalone.py. Do not edit by hand:\n"
          "     edit the modular source and rebuild. -->\n")

os.makedirs('dist', exist_ok=True)
out = 'dist/rnspectrax-standalone.html'
open(out, 'w', encoding='utf-8').write(banner + src)
print('Wrote %s (%.0f KB)' % (out, os.path.getsize(out) / 1024))
